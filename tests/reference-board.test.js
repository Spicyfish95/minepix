import test from 'node:test';
import assert from 'node:assert/strict';
import {createDocument,validateDocument,addLayer,LIMIT} from '../src/model.js';
import {validateReferences,validateBoardItem,boardItemPixels,addReference,removeReference,moveReference,resizeReference,reorderReference,resetReferencePosition,boardBounds,referencePixelCount,BOARD_MIN} from '../src/reference-board.js';
import {referencePixels} from '../src/layer-types.js';
const image=(width,height,rgba=[])=>{const bytes=new Uint8ClampedArray(width*height*4);rgba.forEach((value,index)=>bytes[index]=value);return{width,height,data:btoa(String.fromCharCode(...bytes))};};
const sample=(id='ref-1',name='参考图 1')=>({id,name,...image(2,2,[255,0,0,255,0,255,0,255,0,0,255,255,255,255,255,128]),x:0,y:0,scale:1});
test('参考图片按项目保存并在序列化往返中保持像素与变换',()=>{
 const doc=createDocument(2,2);
 const first=addReference(doc,sample()),second=addReference(doc,{...sample('ref-2','参考图 2'),...image(1,1,[9,8,7,255]),x:-12.5,y:30,scale:2.5});
 assert.equal(doc.references.length,2);
 assert.deepEqual(first,{...sample()});
 assert.equal(second.scale,2.5);
 assert.ok(doc.requiredFeatures.includes('reference-board'));
 const restored=validateDocument(JSON.parse(JSON.stringify(doc)));
 assert.deepEqual(restored,doc);
 assert.equal(restored.references[1].data,second.data);
 assert.ok(restored.requiredFeatures.includes('reference-board'));
 assert.equal(restored.version,2);
});
test('非法 base64、尺寸、位置、缩放与重复 id 明确拒绝',()=>{
 const doc=createDocument(1,1);
 const bad=items=>()=>validateReferences(items);
 assert.throws(bad('not-an-array'),/数组/);
 assert.throws(bad([{...sample(),data:'bad'}]),/完整 RGBA/);
 assert.throws(bad([{...sample(),data:sample().data.slice(0,8)}]),/完整 RGBA/);
 assert.throws(bad([{...sample(),width:0}]),/尺寸/);
 assert.throws(bad([{...sample(),height:1.5}]),/尺寸/);
 assert.throws(bad([{...sample(),x:Infinity}]),/位置/);
 assert.throws(bad([{...sample(),y:1e6+1}]),/位置/);
 assert.throws(bad([{...sample(),scale:0}]),/缩放/);
 assert.throws(bad([{...sample(),scale:17}]),/缩放/);
 assert.throws(bad([{...sample(),id:''}]),/id/);
 assert.throws(bad([{...sample(),name:'   '}]),/名称/);
 assert.throws(bad([sample(),sample()]),/重复/);
 assert.throws(()=>validateBoardItem(null),/无效/);
 assert.throws(()=>validateDocument({...doc,references:[{...sample(),data:'bad'}]}),/完整 RGBA/);
});
